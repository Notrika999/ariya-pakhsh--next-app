export function getIranProvinceNames(): string[] {
  return [...IRAN_PROVINCES];
}

export function getCitiesByProvince(province: string): string[] {
  if (!province) return [];
  const exact = IRAN_CITIES_BY_PROVINCE[province as IranProvince];
  if (exact) return exact;

  const matched = IRAN_PROVINCES.find(
    (name) => name === province || name.includes(province) || province.includes(name),
  );

  return matched ? IRAN_CITIES_BY_PROVINCE[matched] : [];
}

export function resolveIranProvince(value: string): string {
  if (!value) return "";
  if (IRAN_PROVINCES.includes(value as IranProvince)) return value;
  return IRAN_PROVINCES.find((name) => name.includes(value) || value.includes(name)) ?? value;
}
